const makeFlashcards = (seed: DaySeed): Flashcard[] =>
  [...baseFlashcards(seed), ...(seed.dense ? denseFlashcards(seed) : []), ...(seed.extraFlashcards ?? [])]
    .slice(0, seed.dense ? 16 : 12)
    .map((card, index) => ({
      id: `day-${seed.dayNumber}-card-${index + 1}`,
      dayNumber: seed.dayNumber,
      front: card.front,
      back: card.back,
      tags: [...new Set([`day-${seed.dayNumber}`, slug(seed.mainConcept), ...(card.tags ?? [])])],
      difficulty: card.difficulty ?? (index < 4 ? 'easy' : 'medium'),
      sourceType: card.sourceType ?? 'concept',
      relatedCompetencyIds: seed.competencies,
    }))

